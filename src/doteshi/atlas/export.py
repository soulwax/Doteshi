"""Writing an atlas out: page images, atlas.json and a C++ header, all from the same placement records.

atlas.json:
  meta     {name, layout, padding, generator}
  pages    [{file, w, h}]
  sprites  [{name, id, size, variant, page, x, y, w, h,     the rectangle on the page, in pixels
             source: {w, h},                                the size the sprite was rendered at
             trim: {x, y},                                  where the rectangle sat inside that source
             pivot: [x, y],                                 anchor inside the rectangle, in pixels
             living,                                        true for creatures: drawn facing south, to be mirrored
             index, cols, rows}]                            grid layouts only: first cell and the block it spans

In a grid layout x, y, w, h describe the sprite's first cell. A sprite spanning several cells has its piece
(row, col) at x + col * pitch, y + row * pitch; meta carries cell, pitch and columns.
"""
import io
import json
import re

from PIL import Image



def png_bytes(px):
    out = io.BytesIO()
    Image.fromarray(px, "RGBA").save(out, format="PNG", compress_level=9)
    return out.getvalue()


def page_file(name, page):
    return f"{name}.png" if page == 0 else f"{name}_{page}.png"


def to_json(name, layout, padding, lock, grid=None):
    sprites = []
    for key in sorted(lock["sprites"]):
        s = lock["sprites"][key]
        if not s.get("live", True):
            continue
        entry = {"name": key, "id": s["id"], "size": s["size"], "variant": s["variant"], "page": s["page"],
                 "x": s["x"], "y": s["y"], "w": s["w"], "h": s["h"], "source": {"w": s["sw"], "h": s["sh"]},
                 "trim": {"x": s["ox"], "y": s["oy"]}, "pivot": [s["px"], s["py"]]}
        if s.get("living"):
            entry["living"] = True
        for key in ("index", "cols", "rows"):
            if key in s:
                entry[key] = s[key]
        sprites.append(entry)
    data = {"meta": {"name": name, "layout": layout, "padding": padding, "generator": "doteshi", **(grid or {})},
            "pages": [{"file": page_file(name, i), "w": p[0], "h": p[1]} for i, p in enumerate(lock["pages"])],
            "sprites": sprites}
    return json.dumps(data, indent=1) + "\n"


def identifier(name):
    ident = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return ident if not ident[0].isdigit() else "_" + ident


def to_header(name, namespace, lock, grid=None):
    """A header of named constants: one Sprite per entry, usable in constant expressions."""
    live = [(k, s) for k, s in sorted(lock["sprites"].items()) if s.get("live", True)]
    lines = [f"// Generated by doteshi from {name}.lock.json. Do not edit; bake again instead.",
             "#pragma once", "", f"namespace {namespace} {{", "",
             "struct Sprite {",
             "    int page;           // which page image",
             "    int x, y, w, h;     // rectangle on the page, in pixels",
             "    int ox, oy;         // where that rectangle sat inside the untrimmed sprite",
             "    int sw, sh;         // untrimmed sprite size",
             "    float px, py;       // pivot inside the rectangle, in pixels",
             "    int cols, rows;     // cells spanned (1, 1 unless the sprite is a block of grid cells)",
             "    bool living;        // a creature: drawn facing south, mirror it for the other direction",
             "};", "",
             f"inline constexpr int PAGE_COUNT = {len(lock['pages'])};",
             "inline constexpr int PAGE_SIZE[][2] = {" + ", ".join(f"{{{w}, {h}}}" for w, h in lock["pages"]) + "};",
             f"inline constexpr int SPRITE_COUNT = {len(live)};", ""]
    for key, s in live:
        lines.append(f"inline constexpr Sprite {identifier(key)}{{{s['page']}, {s['x']}, {s['y']}, {s['w']}, "
                     f"{s['h']}, {s['ox']}, {s['oy']}, {s['sw']}, {s['sh']}, {s['px']:.1f}f, {s['py']:.1f}f, "
                     f"{s.get('cols', 1)}, {s.get('rows', 1)}, {'true' if s.get('living') else 'false'}}};")
    if grid:
        lines += ["", f"inline constexpr int CELL = {grid['cell']}, PITCH = {grid['pitch']}, "
                      f"COLUMNS = {grid['columns']};",
                  "", "// Piece (row, col) of a sprite that spans several cells, as a sprite of one cell.",
                  "constexpr Sprite piece(const Sprite& s, int row, int col) {",
                  "    return {s.page, s.x + col * PITCH, s.y + row * PITCH, s.w, s.h, col * CELL, row * CELL, "
                  "s.sw, s.sh,",
                  "            s.px - col * CELL, s.py - row * CELL, 1, 1, s.living};", "}"]
    lines += ["", f"}}  // namespace {namespace}", ""]
    return "\n".join(lines)


def files(name, namespace, layout, padding, lock, pages, grid=None):
    """Every output file as {filename: bytes}."""
    out = {page_file(name, i): png_bytes(px) for i, px in enumerate(pages)}
    out[f"{name}.json"] = to_json(name, layout, padding, lock, grid).encode("utf-8")
    out[f"{name}.gen.hpp"] = to_header(name, namespace, lock, grid).encode("utf-8")
    return out
